// Writes the devices table and the wanted list in README.md from the data, so
// no count is ever typed by hand. Contributors never need to run it: a workflow
// does it on main. `node scripts/readme.mjs --check` exits 1 if README.md is stale.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import { parse } from 'yaml';

const root = new URL('..', import.meta.url).pathname;
const dir = join(root, 'src/content/devices');
const ORDER = { verified: 0, works: 1, experimental: 2 };
const METHOD = { jailbreak: 'jailbreak', browser: 'web browser', app: 'app', other: 'other' };
const COMPUTER = { macos: 'macOS', linux: 'Linux', windows: 'Windows' };

const devices = readdirSync(dir)
  .filter((f) => f.endsWith('.md'))
  .map((file) => {
    const fm = readFileSync(join(dir, file), 'utf8').match(/^---\n([\s\S]*?)\n---/);
    if (!fm) throw new Error(`${file}: no frontmatter`);
    return { file, ...parse(fm[1]) };
  })
  .sort((a, b) => ORDER[a.status] - ORDER[b.status] || a.name.localeCompare(b.name));

const rows = devices.map((d) => {
  const name = d.year ? `${d.name} (${d.year})` : d.name;
  const speed = d.latency_ms ? `about ${d.latency_ms} ms` : 'not measured yet';
  const computers = d.computers.map((c) => COMPUTER[c] ?? c).join(', ');
  return `| [${name}](src/content/devices/${d.file}) | ${d.status} | ${METHOD[d.method] ?? d.method} | ${d.input.join(', ')} | ${speed} | ${computers} |`;
});

const wanted = [...readFileSync(join(root, 'src/lib/wanted.ts'), 'utf8').matchAll(/name:\s*'([^']+)'/g)].map(([, n]) =>
  /^(Old|Your|Any) /.test(n) ? n[0].toLowerCase() + n.slice(1) : n,
);
const list = wanted.length > 1 ? `${wanted.slice(0, -1).join(', ')} and ${wanted.at(-1)}` : wanted.join('');
const verified = devices.filter((d) => d.status === 'verified').length;

const START = '<!-- devices:start -->';
const END = '<!-- devices:end -->';
const block = [
  START,
  '<!-- Generated by scripts/readme.mjs from src/content/devices. Edit those files, not this table. -->',
  '',
  `${devices.length} ${devices.length === 1 ? 'screen' : 'screens'} so far, ${verified} verified. Each one has a page with what worked, what didn't and how fast it is.`,
  '',
  '| Device | Status | Method | Input | Tap to action | Computers |',
  '| --- | --- | --- | --- | --- | --- |',
  ...rows,
  '',
  `**Wanted, be the first:** ${list}.`,
  END,
].join('\n');

const path = join(root, 'README.md');
const readme = readFileSync(path, 'utf8');
const from = readme.indexOf(START);
const to = readme.indexOf(END);
if (from < 0 || to < from) throw new Error(`README.md needs the ${START} and ${END} markers`);
const next = readme.slice(0, from) + block + readme.slice(to + END.length);

if (process.argv.includes('--check')) {
  if (next !== readme) {
    console.error('README.md is out of date. Run: node scripts/readme.mjs');
    process.exit(1);
  }
  console.log('readme: up to date');
} else if (next !== readme) {
  writeFileSync(path, next);
  console.log(`readme: table rewritten (${devices.length} ${devices.length === 1 ? 'device' : 'devices'})`);
} else {
  console.log('readme: nothing to change');
}
